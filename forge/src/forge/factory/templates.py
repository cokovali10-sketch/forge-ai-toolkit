"""Factory plugin templates. Real Paper API code, compiled in the lab."""
from __future__ import annotations

import json

GUI_MAIN = r"""package __PKG__;

import net.kyori.adventure.text.Component;
import org.bukkit.Bukkit;
import org.bukkit.Material;
import org.bukkit.command.Command;
import org.bukkit.command.CommandExecutor;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.Listener;
import org.bukkit.event.inventory.InventoryClickEvent;
import org.bukkit.event.player.PlayerJoinEvent;
import org.bukkit.inventory.Inventory;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;
import org.bukkit.plugin.java.JavaPlugin;

public class __CLS__ extends JavaPlugin implements Listener, CommandExecutor {
    private Inventory menu;

    @Override
    public void onEnable() {
        saveDefaultConfig();
        rebuildMenu();
        if (getCommand("__CMD__") != null) {
            getCommand("__CMD__").setExecutor(this);
        }
        getServer().getPluginManager().registerEvents(this, this);
        getLogger().info("__NAME__ enabled (forge-factory)");
    }

    @Override
    public void onDisable() {
        getLogger().info("__NAME__ disabled");
    }

    private void rebuildMenu() {
        menu = Bukkit.createInventory(null, 27,
            Component.text(cfg("menu-title", "__NAME__")));
        menu.setItem(11, icon(Material.DIAMOND, cfg("menu.buy", "Buy")));
        menu.setItem(13, icon(Material.BOOK, cfg("menu.info", "Info")));
        menu.setItem(15, icon(Material.BARRIER, cfg("menu.close", "Close")));
    }

    private String cfg(String path, String fallback) {
        String value = getConfig().getString(path, fallback);
        return value == null ? fallback : value;
    }

    private ItemStack icon(Material material, String label) {
        ItemStack item = new ItemStack(material);
        ItemMeta meta = item.getItemMeta();
        if (meta != null) {
            meta.displayName(Component.text(label));
            item.setItemMeta(meta);
        }
        return item;
    }

    @EventHandler
    public void onJoin(PlayerJoinEvent event) {
        String msg = cfg("join-message", "");
        if (!msg.isEmpty()) {
            event.getPlayer().sendMessage(Component.text(
                msg.replace("%player%", event.getPlayer().getName())));
        }
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command,
                             String label, String[] args) {
        if (args.length > 0 && args[0].equalsIgnoreCase("reload")) {
            reloadConfig();
            rebuildMenu();
            sender.sendMessage(Component.text("__NAME__ reloaded"));
            return true;
        }
        if (!(sender instanceof Player player)) {
            sender.sendMessage(Component.text("__NAME__ console-ok"));
            return true;
        }
        if (args.length > 0 && args[0].equalsIgnoreCase("info")) {
            player.sendMessage(Component.text("__NAME__ v" +
                cfg("version", "__VERSION__")));
            return true;
        }
        player.openInventory(menu);
        player.sendMessage(Component.text(
            cfg("command-reply", "__NAME__ ready")));
        return true;
    }

    @EventHandler
    public void onMenuClick(InventoryClickEvent event) {
        if (menu == null || !event.getInventory().equals(menu)) {
            return;
        }
        event.setCancelled(true);
        if (!(event.getWhoClicked() instanceof Player player)) {
            return;
        }
        int slot = event.getRawSlot();
        if (slot == 15) {
            player.closeInventory();
            player.sendMessage(Component.text(cfg("menu.close-reply", "Closed")));
        } else if (slot == 13) {
            player.sendMessage(Component.text(cfg("menu.info-reply",
                "__NAME__ v" + cfg("version", "__VERSION__"))));
        } else if (slot == 11) {
            player.sendMessage(Component.text(cfg("menu.buy-reply",
                "Added to cart")));
        }
    }
}
"""


def main_source(spec: dict) -> str:
    return (GUI_MAIN
            .replace("__PKG__", spec["package"])
            .replace("__CLS__", spec["class"])
            .replace("__CMD__", spec["command"])
            .replace("__NAME__", spec["name"])
            .replace("__VERSION__", spec["version"]))


def config_yaml(spec: dict) -> str:
    name = spec["name"]
    lines = [
        f"# {name} config (generated by FORGE Factory)",
        f"version: {json.dumps(spec['version'], ensure_ascii=False)}",
        f"join-message: {json.dumps('Welcome %player%!', ensure_ascii=False)}",
        f"command-reply: {json.dumps(f'{name} ready', ensure_ascii=False)}",
        f"menu-title: {json.dumps(name, ensure_ascii=False)}",
        f"menu.buy: {json.dumps('Buy', ensure_ascii=False)}",
        f"menu.info: {json.dumps('Info', ensure_ascii=False)}",
        f"menu.close: {json.dumps('Close', ensure_ascii=False)}",
        f"menu.buy-reply: {json.dumps('Added to cart (demo)', ensure_ascii=False)}",
        f"menu.info-reply: {json.dumps(name + ' v' + spec['version'], ensure_ascii=False)}",
        f"menu.close-reply: {json.dumps('Closed', ensure_ascii=False)}",
        "",
    ]
    return "\n".join(lines)


def readme(spec: dict) -> str:
    return f"""# {spec['name']}

Generated by **FORGE Factory** from the intent:

> {spec['intent']}

- package: `{spec['package']}`
- main: `{spec['package']}.{spec['class']}`
- command: `/{spec['command']}`
- features: {", ".join(spec['features'])}
- theme preset: `{spec['preset']}`

## Build

```bat
forge factory "{spec['intent']}" --out . --name {spec['name']}
```

The factory compiles against a cached `paper-api` jar, boots a real
Purpur/Paper server, runs command scenarios and writes a report + zip.
"""
