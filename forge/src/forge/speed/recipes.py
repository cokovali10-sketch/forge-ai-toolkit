def list_recipes() -> list[dict]:
    return [{"key": key, "title": r["title"], "description": r["description"],
             "lang": r["lang"]} for key, r in sorted(RECIPES.items())]


def build(template: str, name: str, package: str = "",
          extra: dict[str, str] | None = None,
          extra_vars: dict[str, str] | None = None) -> tuple[dict[str, str], dict]:
    key = (template or "python-package").strip().lower()
    vars_ = context(name, package)
    if extra_vars:
        vars_.update({str(k): str(v) for k, v in extra_vars.items()})
    if key == "custom":
        if not extra:
            raise ValueError("custom blueprint needs `files`")
        raw = {str(k): str(v) for k, v in extra.items()}
        return ({render(k, vars_): render(v, vars_) for k, v in raw.items()},
                vars_)
    recipe = RECIPES.get(key)
    if recipe is None:
        raise ValueError("unknown template (есть: "
                         + ", ".join(sorted(RECIPES)) + ", custom)")
    files = recipe["build"](vars_)
    return ({k: render(v, vars_) for k, v in files.items()}, vars_)
