"""Complex, ready-to-run project structures for the Speed department.

Each recipe returns a mapping {relative/path: text}. Placeholders use
``{{name}}``, ``{{slug}}``, ``{{module}}``, ``{{class}}``, ``{{package}}``,
``{{package_path}}``, ``{{title}}`` and ``{{year}}``.
"""
from __future__ import annotations

import re
from typing import Callable

_TAG = re.compile(r"\{\{([a-zA-Z_][a-zA-Z0-9_]*)\}\}")


def slugify(name: str, sep: str = "-") -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", sep, name).strip(sep).lower()
    return s or "forge-app"


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"[^a-zA-Z0-9]+", "_", s).strip("_").lower()
    if not s:
        return "forge_app"
    return "app_" + s if s[0].isdigit() else s


def pascal(name: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not out:
        return "ForgeApp"
    if out[0].isdigit():
        out = "App" + out
    return out


def context(name: str, package: str = "") -> dict[str, str]:
    slug = slugify(name)
    module = snake(name)
    cls = pascal(name)
    return {
        "name": name or "Forge App",
        "title": name or "Forge App",
        "slug": slug,
        "module": module,
        "class": cls,
        "package": package or f"com.forge.{module}",
        "package_path": (package or f"com.forge.{module}").replace(".", "/"),
        "year": "2026",
    }


def render(text: str, vars_: dict[str, str]) -> str:
    """Replace {{placeholders}}; unknown placeholders are an error."""
    missing: set[str] = set()

    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in vars_:
            missing.add(key)
            return m.group(0)
        return str(vars_[key])

    out = _TAG.sub(sub, text)
    if missing:
        raise ValueError("unknown template variables: " + ", ".join(sorted(missing)))
    return out


