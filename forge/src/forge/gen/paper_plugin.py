"""Paper plugin generator. Scaffold -> validated files, no invented APIs.

Generates: plugin.yml, Main (commands + join listener + config),
README. Compiles via lab.build against cached paper-api, boots in lab.
"""
from __future__ import annotations

import re
from pathlib import Path

MAIN_TMPL = """package {pkg};

import org.bukkit.command.Command;
import org.bukkit.command.CommandExecutor;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.Listener;
import org.bukkit.event.player.PlayerJoinEvent;
import org.bukkit.plugin.java.JavaPlugin;

public class {cls} extends JavaPlugin implements Listener, CommandExecutor {{
    @Override
    public void onEnable() {{
        saveDefaultConfig();
        if (getCommand("{command}") != null) {{
            getCommand("{command}").setExecutor(this);
        }}
        getServer().getPluginManager().registerEvents(this, this);
        getLogger().info("{name} enabled (forge-generated)");
    }}

    @EventHandler
    public void onJoin(PlayerJoinEvent e) {{
        String msg = getConfig().getString("join-message", "");
        if (!msg.isEmpty()) {{
            e.getPlayer().sendMessage(msg.replace("%player%", e.getPlayer().getName()));
        }}
    }}

    @Override
    public boolean onCommand(CommandSender sender, Command cmd, String label, String[] args) {{
        if (!(sender instanceof Player player)) {{
            sender.sendMessage("{name} console-ok");
            return true;
        }}
        player.sendMessage(getConfig().getString("command-reply", "Hello from {name}!"));
        return true;
    }}
}}
"""

PLUGIN_YML = """name: {name}
version: {version}
main: {pkg}.{cls}
api-version: '{api}'
author: FORGE Generator
description: {description}
commands:
  {command}:
    description: Main command
    usage: /{command}
"""


def _slug(name: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "", name)
    if not slug or not slug[0].isalpha():
        raise ValueError(f"bad plugin name: {name!r}")
    return slug[0].upper() + slug[1:]


def generate(out_dir: str | Path, name: str, package: str = "com.forge.demo",
             command: str = "hello", description: str = "",
             api: str = "1.21", version: str = "0.1.0") -> dict:
    """Generates a plugin project. Returns {dir, files, main_class}."""
    if not re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", package):
        raise ValueError(f"bad package: {package!r}")
    if not re.fullmatch(r"[a-z][a-z0-9_]*", command):
        raise ValueError(f"bad command: {command!r}")
    cls = _slug(name)
    out = Path(out_dir)
    src = out / "src" / Path(*package.split("."))
    src.mkdir(parents=True, exist_ok=True)
    files = {}
    files["main"] = src / f"{cls}.java"
    files["main"].write_text(MAIN_TMPL.format(
        pkg=package, cls=cls, name=name, command=command), encoding="utf-8")
    files["plugin.yml"] = out / "src" / "plugin.yml"
    files["plugin.yml"].write_text(PLUGIN_YML.format(
        name=name, version=version, pkg=package, cls=cls, api=api,
        command=command,
        description=description or f"{name} by FORGE"), encoding="utf-8")
    files["config"] = out / "src" / "config.yml"
    files["config"].write_text(
        f"# {name} config\njoin-message: \"Welcome %player%!\"\n"
        f"command-reply: \"Hello from {name}!\"\n", encoding="utf-8")
    files["readme"] = out / "README.md"
    files["readme"].write_text(
        f"# {name}\n\nGenerated by FORGE. Build: javac vs paper-api, "
        f"or drop into a gradle project.\n", encoding="utf-8")
    return {"dir": str(out), "main_class": f"{package}.{cls}",
            "files": {k: str(v) for k, v in files.items()}}
