"""Node API generator: HTTP-сервис на встроенном `node:http`, ноль зависимостей.

Generates: package.json, server.js (GET /health, GET /hello), test/server.test.js
(встроенный `node --test`), README, .gitignore.
Проверяется: скобки JS сходятся, есть обязательные ключи.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

SERVER = """'use strict';
const http = require('node:http');

function greeting(name) {
  var who = name && String(name).trim() ? String(name).trim() : 'world';
  return 'hello ' + who;
}

function createServer() {
  return http.createServer(function (req, res) {
    var url = new URL(req.url, 'http://localhost');
    if (url.pathname === '/health') {
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ status: 'ok' }));
      return;
    }
    if (url.pathname === '/hello') {
      var msg = greeting(url.searchParams.get('name') || '');
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ message: msg }));
      return;
    }
    res.writeHead(404);
    res.end();
  });
}

if (require.main === module) {
  var port = process.env.PORT || 3000;
  createServer().listen(port, function () {
    console.log('listening on ' + port);
  });
}

module.exports = { greeting: greeting, createServer: createServer };
"""

TEST = """'use strict';
const test = require('node:test');
const assert = require('node:assert');
const { greeting, createServer } = require('../server.js');

test('greeting defaults to world', function () {
  assert.strictEqual(greeting(''), 'hello world');
  assert.strictEqual(greeting('Ada'), 'hello Ada');
});

test('health endpoint answers ok', async function () {
  const srv = createServer();
  await new Promise(function (r) { srv.listen(0, r); });
  const port = srv.address().port;
  const res = await fetch('http://127.0.0.1:' + port + '/health');
  assert.strictEqual(res.status, 200);
  const data = await res.json();
  assert.strictEqual(data.status, 'ok');
  srv.close();
});
"""


def _slug(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9-_]", "-", (name or "api")).strip("-").lower()
    return s or "api"


def generate(out_dir: str | Path, name: str = "api") -> dict:
    """Generates a Node HTTP API. Returns {dir, files, ok, problems}."""
    safe = _slug(name)
    out = Path(out_dir)
    pkg = {"name": safe, "version": "0.1.0", "private": True,
           "description": "Node HTTP API generated by FORGE",
           "scripts": {"start": "node server.js", "test": "node --test"}}
    files = {
        "package.json": json.dumps(pkg, ensure_ascii=False, indent=2) + "\n",
        "server.js": SERVER,
        "test/server.test.js": TEST,
        "README.md": f"# {safe}\n\n`npm start` (PORT=3000), `npm test`.\n"
                     "Маршруты: `GET /health`, `GET /hello?name=Ada`.\n",
        ".gitignore": "node_modules/\n",
    }
    made = []
    for rel, content in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        made.append(rel)
    problems = []
    js = SERVER
    for ch_open, ch_close in (("{", "}"), ("(", ")")):
        if js.count(ch_open) != js.count(ch_close):
            problems.append(f"server.js: {ch_open}{ch_close} не сходятся")
    try:
        json.loads(files["package.json"])
    except ValueError:
        problems.append("package.json: невалидный JSON")
    return {"dir": str(out), "files": made, "ok": not problems,
            "problems": problems}
